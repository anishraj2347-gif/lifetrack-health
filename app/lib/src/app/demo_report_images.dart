import 'dart:typed_data';

import 'package:image/image.dart' as img;

/// Picture of a paper report for the SAMPLE profile only, so the demo can
/// show "view original". Stamped as a sample in two places; never used for
/// a real profile.
abstract final class DemoReportImages {
  static Uint8List render({
    required String lab,
    required String title,
    required String patient,
    required String date,
    required List<(String test, String value, String unit, String range)> rows,
  }) {
    final im = img.Image(width: 1240, height: 1754); // A4 at 150 dpi
    img.fill(im, color: img.ColorRgb8(252, 252, 248));
    final ink = img.ColorRgb8(20, 20, 20);
    final grey = img.ColorRgb8(110, 110, 110);
    final red = img.ColorRgb8(194, 65, 12);

    img.drawString(im, lab.toUpperCase(), font: img.arial48, x: 80, y: 80, color: ink);
    img.drawString(im, 'SAMPLE - NOT A REAL LAB REPORT', font: img.arial24, x: 80, y: 150, color: red);
    img.drawLine(im, x1: 80, y1: 200, x2: 1160, y2: 200, color: ink, thickness: 3);
    img.drawString(im, 'Patient: $patient', font: img.arial24, x: 80, y: 230, color: ink);
    img.drawString(im, 'Sample collected: $date', font: img.arial24, x: 80, y: 270, color: ink);
    img.drawString(im, title, font: img.arial48, x: 80, y: 340, color: ink);

    img.drawString(im, 'TEST', font: img.arial24, x: 80, y: 440, color: grey);
    img.drawString(im, 'RESULT', font: img.arial24, x: 560, y: 440, color: grey);
    img.drawString(im, 'UNIT', font: img.arial24, x: 760, y: 440, color: grey);
    img.drawString(im, 'REFERENCE', font: img.arial24, x: 920, y: 440, color: grey);
    img.drawLine(im, x1: 80, y1: 480, x2: 1160, y2: 480, color: grey);
    var y = 510;
    for (final (t, v, u, r) in rows) {
      img.drawString(im, t, font: img.arial24, x: 80, y: y, color: ink);
      img.drawString(im, v, font: img.arial24, x: 560, y: y, color: ink);
      img.drawString(im, u, font: img.arial24, x: 760, y: y, color: ink);
      img.drawString(im, r, font: img.arial24, x: 920, y: y, color: ink);
      y += 60;
    }
    img.drawLine(im, x1: 80, y1: 1560, x2: 1160, y2: 1560, color: grey);
    img.drawString(im, 'Generated by LifeTrack for demonstration. Not a medical document.', font: img.arial24, x: 80, y: 1590, color: red);
    return img.encodeJpg(im, quality: 80);
  }
}
